"""Regenerate benchmark/apps.json, docker-compose.yml and per-app READMEs from the app definitions."""
import importlib
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from common.framework import BENCH_KEY, BASE_USERS, DEMO_PASSWORD  # noqa: E402

IDS = ["invoiceflow", "taskboard", "formstacker", "bookly", "stockpilot", "supportdesk", "mailforge", "expensetrack", "teampulse", "clienthub",
       "eventpilot", "coursecloud", "contractvault", "surveylab", "recruitflow", "assetmanager", "timetrack", "quotepro", "analyticshub", "subscriptionpilot"]
ORGS = {1: "Acme Corp", 2: "Globex Inc"}


def load(i):
    app = importlib.import_module(f"apps.{i}.app").app
    app._add_defaults()
    return app


def readme(app):
    rows = "\n".join(f"| {m} | `{p}` | {'public' if not a else (', '.join(r) if r else 'any signed-in user')} | {(f.__doc__ or '').strip()} |"
                     for m, _, p, a, r, f in app.routes if p.startswith("/api") and not p.startswith(("/api/docs", "/api/auth")))
    creds = "\n".join(f"| {e} | `{DEMO_PASSWORD}` | {r} | {ORGS[o]} |" for _, o, e, _, r in BASE_USERS)
    return f"""# {app.name}

{app.description}

This is a synthetic benchmark application. It is a small, early-stage product with imperfect production code;
the intended behaviour is whatever a reasonable product of this kind should do.

- Frontend: open `http://127.0.0.1:{app.port}/` (sign in with a demo account).
- API docs: `GET /api/docs`. Health: `GET /health`.
- Data: SQLite, deterministic seed data, fixed application clock (2026-03-15 10:00 UTC, a Sunday).
- Multi-tenant: two organisations. Users only ever belong to one.
- Money is in integer cents, dates are ISO-8601.

## Demo credentials

| Email | Password | Role | Organisation |
|---|---|---|---|
{creds}

Log in with `POST /api/auth/login {{"email","password"}}`, then send `Authorization: Bearer <token>`.

## API

| Method | Path | Roles | Notes |
|---|---|---|---|
{rows}

## Reset

`POST /__benchmark/reset` with header `X-Benchmark-Key: <BENCH_KEY>` (default `{BENCH_KEY}`) restores the database and seed data.

## Run

```bash
python -m common.run {app.id}            # from the repository root; port {app.port}
```
"""


def main():
    apps = [load(i) for i in IDS]
    meta = {"version": 1, "reset_header": "X-Benchmark-Key", "apps": []}
    for a in apps:
        base = f"http://127.0.0.1:{a.port}"
        meta["apps"].append({
            "id": a.id, "name": a.name, "description": a.description, "port": a.port, "base_url": base,
            "health_url": base + "/health", "docs_url": base + "/api/docs", "login_url": base + "/api/auth/login",
            "reset": {"method": "POST", "url": base + "/__benchmark/reset", "headers": {"X-Benchmark-Key": BENCH_KEY}},
            "credentials": [{"email": e, "password": DEMO_PASSWORD, "role": r, "organization": ORGS[o]} for _, o, e, _, r in BASE_USERS],
            "readme": f"apps/{a.id}/README.md", "start_command": f"python -m common.run {a.id}"})
        (ROOT / "apps" / a.id / "README.md").write_text(readme(a))
    (ROOT / "benchmark" / "apps.json").write_text(json.dumps(meta, indent=2) + "\n")
    svc = "".join(f"""  {a.id}:
    build: .
    command: python -m common.run {a.id} --host 0.0.0.0 --port {a.port}
    ports: ["{a.port}:{a.port}"]
    environment: [BENCH_KEY=${{BENCH_KEY:-{BENCH_KEY}}}, BENCH_DATA_DIR=/data]
    volumes: ["{a.id}-data:/data"]
    healthcheck: {{test: ["CMD", "python", "-c", "import urllib.request as u; u.urlopen('http://127.0.0.1:{a.port}/health')"], interval: 5s, retries: 10}}
""" for a in apps)
    vols = "".join(f"  {a.id}-data:\n" for a in apps)
    (ROOT / "docker-compose.yml").write_text(f"# Generated by scripts/generate.py. Images contain only common/ and apps/ (no tests, no benchmark/ manifests).\nservices:\n{svc}volumes:\n{vols}")
    print(f"generated {len(apps)} apps")


if __name__ == "__main__":
    main()
